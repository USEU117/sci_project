def set_east_asia_font(run, font_name: str) -> None:
    run.font.name = font_name
    run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), font_name)


def replace_paragraph_text(paragraph, text: str) -> None:
    if paragraph.runs:
        lead = paragraph.runs[0]
        lead.text = text
        for run in list(paragraph.runs[1:]):
            run._element.getparent().remove(run._element)
    else:
        lead = paragraph.add_run(text)

    if paragraph.style.name.startswith("Heading"):
        set_east_asia_font(lead, "Microsoft YaHei")
    else:
        set_east_asia_font(lead, "SimSun")


def main() -> None:
    doc = Document(SOURCE)
    if len(doc.paragraphs) != 92:
        raise RuntimeError(f"Unexpected paragraph count: {len(doc.paragraphs)}")

    for index, translated in TRANSLATIONS.items():
        replace_paragraph_text(doc.paragraphs[index], translated)

    for section in doc.sections:
        for paragraph in section.header.paragraphs:
            if "DCFnet" in paragraph.text:
                replace_paragraph_text(paragraph, "DCFnet｜中文对照译稿（至方法部分）")

    for shape in doc.inline_shapes:
        doc_pr = shape._inline.docPr
        doc_pr.set("title", "DCFnet 总体架构")
